-- =====================================================================
-- Core schema for the IITM BS esports platform.
--
-- Security model (read this before touching anything):
--   * Every table has RLS on. anon/authenticated get SELECT on a few
--     tables only, and never INSERT/UPDATE/DELETE. All writes go through
--     SECURITY DEFINER functions below, which validate everything.
--   * Private data (email, WhatsApp) lives in public.profiles, which a
--     user can read only for their own row. Everything public about a
--     player (username, house) is served by RPCs that pick columns.
--   * Roles live in public.user_roles, never in user_metadata (which the
--     user can edit from the client).
--   * Every function has search_path = '' and names everything in full.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 0. Lock down defaults: nothing new is reachable unless granted here.
-- ---------------------------------------------------------------------
alter default privileges in schema public revoke all on tables from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;
alter default privileges in schema public revoke execute on functions from public, anon, authenticated;
-- The per-schema rule above cannot remove the global EXECUTE-to-PUBLIC default; this one does.
alter default privileges revoke execute on functions from public;

