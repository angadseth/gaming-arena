-- Identity fields never change once set, even for admins via SQL mistakes.
create function public.profiles_freeze_identity() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.id <> old.id or new.email <> old.email or new.username <> old.username then
    raise exception 'Username and email cannot be changed' using errcode = 'P0001', hint = 'IMMUTABLE';
  end if;
  return new;
end $$;

