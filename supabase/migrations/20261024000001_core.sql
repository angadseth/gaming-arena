create function public.email_domain_allowed(p_email text) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1
    from public.app_settings s,
         jsonb_array_elements_text(s.value) d(domain)
    where s.key = 'allowed_email_domains'
      and lower(btrim(p_email)) ~ '^[a-z0-9][a-z0-9._-]{0,63}@[a-z0-9.-]+$'
      and split_part(lower(btrim(p_email)), '@', 2) = lower(d.domain)
  )
$$;

-- Sessions must come from the emailed code: never a password or anonymous sign-in.
create function public.session_ok() returns boolean
language sql stable set search_path = '' as $$
  select coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) = false
     and not exists (select 1 from jsonb_array_elements(coalesce(auth.jwt() -> 'amr', '[]')) a
                     where a ->> 'method' in ('password', 'anonymous'))
$$;

create function public.has_role(p_roles text[]) returns boolean
language sql stable security definer set search_path = '' as $$
  select public.session_ok() and exists (
    select 1 from public.user_roles r
    join public.profiles p on p.id = r.user_id
    where r.user_id = auth.uid() and r.role = any (p_roles) and p.status = 'active'
  )
$$;

create function public.is_admin() returns boolean
language sql stable set search_path = '' as $$
  select public.has_role(array['superadmin', 'admin'])
$$;

create function public.is_staff() returns boolean
language sql stable set search_path = '' as $$
  select public.has_role(array['superadmin', 'admin', 'organizer'])
$$;

create function public.require_admin() returns void
language plpgsql stable set search_path = '' as $$
begin
  if not public.is_admin() then
    raise exception 'Admins only' using errcode = '42501', hint = 'FORBIDDEN';
  end if;
end $$;

-- The caller's active profile, or an error.
create function public.require_player() returns public.profiles
language plpgsql stable security definer set search_path = '' as $$
declare
  v public.profiles;
begin
  if auth.uid() is null then
    raise exception 'Please sign in first' using errcode = '42501', hint = 'AUTH_REQUIRED';
  end if;
  if not public.session_ok() then
    raise exception 'Sign in with the emailed code' using errcode = '42501', hint = 'AUTH_METHOD';
  end if;
  select * into v from public.profiles where id = auth.uid();
  if not found then
    raise exception 'Finish your profile first' using errcode = 'P0001', hint = 'PROFILE_REQUIRED';
  end if;
  if v.status <> 'active' then
    raise exception 'Your account is %', v.status using errcode = '42501', hint = 'ACCOUNT_BLOCKED';
  end if;
  return v;
end $$;

