-- Per-user throttle for player writes, so one account cannot flood the database.
create table public.rate_events (
  user_id uuid not null,
  action  text not null,
  at      timestamptz not null default now()
);
create index rate_events_idx on public.rate_events (user_id, action, at);
alter table public.rate_events enable row level security;

create function public.throttle(p_action text, p_max int, p_window interval) returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform pg_advisory_xact_lock(hashtextextended(auth.uid()::text || p_action, 0));
  if (select count(*) from public.rate_events
      where user_id = auth.uid() and action = p_action and at > now() - p_window) >= p_max then
    raise exception 'Slow down and try again shortly' using errcode = 'P0001', hint = 'RATE_LIMITED';
  end if;
  insert into public.rate_events (user_id, action) values (auth.uid(), p_action);
  delete from public.rate_events where at < now() - interval '2 days' and random() < 0.01;
end $$;

create function public.new_invite_code() returns text
language plpgsql volatile set search_path = '' as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  bytes bytea := decode(replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''), 'hex');
  code text := '';
  i int;
begin
  for i in 0..7 loop
    -- byte 6 of a UUIDv4 carries the version nibble, so use byte 9 instead.
    code := code || substr(alphabet, (get_byte(bytes, case when i = 6 then 9 else i end) % 32) + 1, 1);
  end loop;
  return code;
end $$;

create function public.normalize_whatsapp(p text) returns text
language plpgsql immutable set search_path = '' as $$
declare
  d text := regexp_replace(coalesce(p, ''), '[\s()-]', '', 'g');
begin
  if d ~ '^[6-9][0-9]{9}$' then
    return '+91' || d;
  elsif d ~ '^(0|91)[6-9][0-9]{9}$' then
    return '+91' || right(d, 10);
  elsif d ~ '^\+[1-9][0-9]{7,14}$' then
    return d;
  end if;
  raise exception 'Enter a valid WhatsApp number' using errcode = 'P0001', hint = 'BAD_WHATSAPP';
end $$;

-- A tournament accepts registrations right now?
create function public.registration_open(t public.tournaments) returns boolean
language sql stable set search_path = '' as $$
  select t.status = 'open'
     and (t.reg_opens_at is null or now() >= t.reg_opens_at)
     and (t.reg_closes_at is null or now() < t.reg_closes_at)
$$;

-- Looks up points for a rank in a table like {"1": 10, "2": 6, "5-8": 2}.
-- Exact keys win over ranges; unknown ranks score 0.
create function public.points_for_rank(p_table jsonb, p_rank int) returns numeric
language sql immutable set search_path = '' as $$
  select coalesce(
    (p_table ->> p_rank::text)::numeric,
    (select (v)::numeric from jsonb_each_text(p_table) e(k, v)
     where k ~ '^[0-9]+-[0-9]+$'
       and p_rank between split_part(k, '-', 1)::int and split_part(k, '-', 2)::int
     limit 1),
    0)
  where p_rank is not null
$$;

-- Validates an in-game ID and extra fields against the game's config.
-- Returns the cleaned extra object.
create function public.validate_game_fields(g public.games, p_ig_id text, p_extra jsonb) returns jsonb
language plpgsql stable set search_path = '' as $$
declare
  f jsonb;
  k text;
  v text;
  cleaned jsonb := '{}';
  allowed text[] := '{}';
begin
  if p_ig_id is null or btrim(p_ig_id) = '' or char_length(btrim(p_ig_id)) > 64
     or btrim(p_ig_id) !~ g.ig_id_pattern then
    raise exception 'That % does not look right. %', g.ig_id_label, g.ig_id_hint
      using errcode = 'P0001', hint = 'BAD_IG_ID';
  end if;

  p_extra := coalesce(p_extra, '{}');
  if jsonb_typeof(p_extra) <> 'object' then
    raise exception 'Bad extra fields' using errcode = 'P0001', hint = 'BAD_EXTRA';
  end if;

  for f in select * from jsonb_array_elements(g.extra_fields) loop
    k := f ->> 'key';
    allowed := allowed || k;
    v := btrim(coalesce(p_extra ->> k, ''));
    if v = '' then
      if coalesce((f ->> 'required')::boolean, true) then
        raise exception '% is required', f ->> 'label' using errcode = 'P0001', hint = 'BAD_EXTRA';
      end if;
      continue;
    end if;
    if char_length(v) > 80 or (f ? 'pattern' and v !~ (f ->> 'pattern')) then
      raise exception '% does not look right. %', f ->> 'label', coalesce(f ->> 'hint', '')
        using errcode = 'P0001', hint = 'BAD_EXTRA';
    end if;
    cleaned := cleaned || jsonb_build_object(k, v);
  end loop;

  for k in select jsonb_object_keys(p_extra) loop
    if not (k = any (allowed)) then
      raise exception 'Unknown field %', k using errcode = 'P0001', hint = 'BAD_EXTRA';
    end if;
  end loop;

  return cleaned;
end $$;

-- ---------------------------------------------------------------------
-- 9. Auth guard: only allowed IITM domains may ever become users.
--    Wired as the "Before User Created" auth hook, and repeated as a
--    trigger so a misconfigured hook still cannot let anyone in.
-- ---------------------------------------------------------------------
create function public.hook_before_user_created(event jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  v_email text := lower(coalesce(event -> 'user' ->> 'email', ''));
begin
  if not public.email_domain_allowed(v_email) then
    return jsonb_build_object('error', jsonb_build_object(
      'http_code', 403,
      'message', 'Only IIT Madras BS student emails can sign in.'));
  end if;
  return '{}'::jsonb;
end $$;

create function public.guard_auth_user_domain() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'UPDATE' and old.email is not null and new.email is distinct from old.email then
    raise exception 'Email cannot be changed.' using errcode = '42501';
  end if;
  if new.email is null or not public.email_domain_allowed(new.email) then
    raise exception 'Only IIT Madras BS student emails can sign in.' using errcode = '42501';
  end if;
  return new;
end $$;

create trigger guard_domain before insert or update of email on auth.users
  for each row execute function public.guard_auth_user_domain();

