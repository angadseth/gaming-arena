// Builds the games seed migration from docs/research/games.json.
// Run: node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const games = JSON.parse(readFileSync(new URL('../docs/research/games.json', import.meta.url), 'utf8'))
const OUT = new URL('../supabase/migrations/20261024000004_seed_games.sql', import.meta.url)

// Placement tables from the research (BGIS 2024-26, FFMIC 2026, F1-style).
const POINTS = {
  bgmi: [{ 1: 10, 2: 6, 3: 5, 4: 4, 5: 3, 6: 2, '7-8': 1 }, 1],
  'ff-max': [{ 1: 12, 2: 9, 3: 8, 4: 7, 5: 6, 6: 5, 7: 4, 8: 3, 9: 2, 10: 1 }, 1],
  'asphalt-legends': [{ 1: 10, 2: 8, 3: 6, 4: 5, 5: 4, 6: 3, 7: 2, 8: 1 }, 0],
  'stumble-guys': [{ 1: 10, 2: 7, 3: 5 }, 0],
}
const DEFAULT_POINTS = [{ 1: 10, 2: 7, 3: 5, 4: 4, '5-8': 2, '9-16': 1 }, 0]

const lit = (s) => `$q$${String(s)}$q$`
const json = (v) => `$j$${JSON.stringify(v)}$j$::jsonb`

const rows = games.map((g, i) => {
  // Team name is asked when the team is created, never as an extra field.
  const extra = (g.extraFields ?? []).filter((f) => f.key !== 'teamName')
    .map((f) => ({ ...f, required: f.required ?? true }))
  const [placement, kill] = POINTS[g.slug] ?? DEFAULT_POINTS
  const maxSubs = g.teamSize > 1 ? 1 : 0
  return `  (${lit(g.slug)}, ${lit(g.title)}, ${lit(g.short ?? '')}, ${lit(g.format ?? '')},
   array[${g.platforms.map(lit).join(', ')}]::text[], ${lit(g.mode)}, ${g.teamSize}, ${maxSubs},
   ${lit(g.igIdLabel)}, ${lit(g.igIdPattern)}, ${lit(g.igIdHint ?? '')},
   ${json(extra)}, ${json(g.rules ?? [])}, ${lit(g.scoring ?? '')},
   ${json(placement)}, ${kill}, ${g.matchMinutes ?? 'null'}, ${lit(g.verify ?? '')}, ${i + 1})`
})

const sql = `-- Generated by scripts/gen-seed.mjs from docs/research/games.json. Do not edit by hand.
insert into public.games (slug, title, short, description, platforms, mode, team_size, max_subs,
  ig_id_label, ig_id_pattern, ig_id_hint, extra_fields, rules, scoring,
  placement_points, kill_points, match_minutes, verify_note, sort_order)
values
${rows.join(',\n')};

-- One Season 1 event per game, announced but not yet open. Admins set
-- dates and open registration from the panel.
insert into public.tournaments (game_id, slug, title, season, summary, status, placement_points, kill_points, same_house_teams)
select g.id, g.slug || '-s1', coalesce(nullif(g.short, ''), g.title) || ' Season 1', 'S1',
       'Season 1 of the IITM BS ' || g.title || ' tournament. Dates are announced here and on the official WhatsApp group.',
       'upcoming', g.placement_points, g.kill_points, false
from public.games g;
`
writeFileSync(OUT, sql)
console.log(`wrote ${games.length} games to ${OUT.pathname}`)
